  function setupCommandPalette() {
    const root = document.getElementById("cmd");
    const input = document.getElementById("cmdInput");
    const list = document.getElementById("cmdList");
    const opener = document.getElementById("cmdOpen");
    if (!root || !input || !list) return;
    let visible = [];
    let returnFocus = null;
    const render = () => {
      const query = input.value.trim().toLowerCase();
      visible = getCommands().filter((command) => command.label.toLowerCase().includes(query));
      list.innerHTML = visible.length ? visible.map((command, index) => `<li><button type="button" class="cmd-item" data-cmd="${index}">${escapeHtml(command.label)}</button></li>`).join("") : `<li class="cmd-empty">${escapeHtml(copy[currentLanguage].cmdEmpty)}</li>`;
    };
    const open = () => {
      if (!root.hidden) return;
      returnFocus = document.activeElement;
      root.hidden = false;
      input.value = "";
      render();
      input.focus();
    };
    const close = () => {
      if (root.hidden) return;
      root.hidden = true;
      if (returnFocus instanceof HTMLElement) returnFocus.focus();
    };
    const run = (command) => {
      close();
      if (command) command.run();
    };
    const items = () => Array.from(list.querySelectorAll(".cmd-item"));
    if (opener) opener.addEventListener("click", open);
    document.addEventListener("keydown", (event) => {
      if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k") {
        event.preventDefault();
        if (root.hidden) open();
        else close();
        return;
      }
      if (root.hidden) return;
      if (event.key === "Escape") {
        event.preventDefault();
        close();
      } else if (event.key === "Tab") {
        const focusable = [input, ...items()];
        const index = focusable.indexOf(document.activeElement);
        const next = event.shiftKey ? index - 1 : index + 1;
        event.preventDefault();
        focusable[(next + focusable.length) % focusable.length].focus();
      }
    });
    input.addEventListener("input", render);
    input.addEventListener("keydown", (event) => {
      if (event.key === "ArrowDown") {
        event.preventDefault();
        const first = items()[0];
        if (first) first.focus();
      } else if (event.key === "Enter") {
        event.preventDefault();
        run(visible[0]);
      }
    });
    list.addEventListener("keydown", (event) => {
      const buttons = items();
      const index = buttons.indexOf(document.activeElement);
      if (index === -1) return;
      if (event.key === "ArrowDown") {
        event.preventDefault();
        buttons[Math.min(index + 1, buttons.length - 1)].focus();
      } else if (event.key === "ArrowUp") {
        event.preventDefault();
        if (index === 0) input.focus();
        else buttons[index - 1].focus();
      }
    });
    list.addEventListener("click", (event) => {
      const button = event.target.closest(".cmd-item");
      if (button) run(visible[Number(button.dataset.cmd)]);
    });
    root.addEventListener("mousedown", (event) => {
      if (event.target === root) close();
    });
  }
